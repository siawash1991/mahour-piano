export type Step = {
  midi: number;
  beats: number;
  hand?: "R" | "L";
  finger?: number;
  chord?: number[];
};
export type Lesson = {
  id: string;
  level: number;
  title: string;
  subtitle: string;
  minutes: number;
  concept: string;
  instructions: string[];
  steps: Step[];
  bpm: number;
  kind: "lesson" | "song";
  credit?: string;
};
const seq = (
  notes: number[],
  beats: number[] = [],
  hand: "R" | "L" = "R",
): Step[] => notes.map((midi, i) => ({ midi, beats: beats[i] ?? 1, hand }));
